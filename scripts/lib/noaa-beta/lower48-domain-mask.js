function isPointInLower48Mainland(lat, lon) {
  const y = Number(lat);
  const x = Number(lon);
  if (!Number.isFinite(x) || !Number.isFinite(y) || y < 24 || y > 50 || x < -125 || x > -66) {
    return false;
  }
  let inside = false;
  for (
    let index = 0, previous = LOWER48_MAINLAND_POLYGON_0P2_DEG.length - 1;
    index < LOWER48_MAINLAND_POLYGON_0P2_DEG.length;
    previous = index, index += 1
  ) {
    const [xi, yi] = LOWER48_MAINLAND_POLYGON_0P2_DEG[index];
    const [xj, yj] = LOWER48_MAINLAND_POLYGON_0P2_DEG[previous];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

function lower48LongitudeIntervalsAtLatitude(lat) {
  const y = Number(lat);
  if (!Number.isFinite(y)) {
    return [];
  }
  const intersections = [];
  for (let index = 1; index < LOWER48_MAINLAND_POLYGON_0P2_DEG.length; index += 1) {
    const [x1, y1] = LOWER48_MAINLAND_POLYGON_0P2_DEG[index - 1];
    const [x2, y2] = LOWER48_MAINLAND_POLYGON_0P2_DEG[index];
    if (y1 > y === y2 > y) {
      continue;
    }
    intersections.push(x1 + ((y - y1) * (x2 - x1)) / (y2 - y1));
  }
  intersections.sort((left, right) => left - right);
  const intervals = [];
  for (let index = 0; index + 1 < intersections.length; index += 2) {
    intervals.push([intersections[index], intersections[index + 1]]);
  }
  return intervals;
}

